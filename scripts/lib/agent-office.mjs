/*
 * The one place the Agent Office's per-environment configuration is written
 * (docs/sdd/agent-office-live/spec.md R41, R48, R65; plan.md "Hosting layout").
 *
 * The pure half; the command line wrapper is scripts/agent-office-config.mjs, which writes
 * agent-office/wrangler.toml and agent-office/public/version.txt for
 * .github/workflows/deploy-agent-office.yml right before `wrangler pages deploy`. Neither file is
 * committed.
 *
 * Plain variables only: the Pages project, the one origin CORS grants (`APP_ORIGIN`, the page's own
 * origin, since page and middleware share the project), and the Firebase project whose ID tokens
 * and `users/{uid}` records the middleware checks. No secret exists on these projects (R41, main
 * thread design change of 16 Oct 2026); GitHub is read in the workflow, not here.
 */
export const COMPATIBILITY_DATE = '2026-05-01';

export const AGENT_OFFICE_ENVIRONMENTS = {
  staging: {
    project: 'agent-office-staging',
    appOrigin: 'https://agent-office-staging.pages.dev',
    firebaseProjectId: 'taskfolio-staging',
  },
  prod: {
    project: 'agent-office-prod',
    appOrigin: 'https://agent-office-prod.pages.dev',
    firebaseProjectId: 'taskfolio-prod',
  },
};

function tomlString(value) {
  if (!/^[A-Za-z0-9:/._-]+$/.test(value)) throw new Error(`Refusing to write an unexpected value into wrangler.toml: ${value}`);
  return `"${value}"`;
}

/** The wrangler.toml text for `name` (`staging` or `prod`); throws for any other name. */
export function wranglerToml(name) {
  if (!Object.hasOwn(AGENT_OFFICE_ENVIRONMENTS, name)) {
    throw new Error(`Unknown environment "${name}". Expected one of: ${Object.keys(AGENT_OFFICE_ENVIRONMENTS).join(', ')}`);
  }
  const env = AGENT_OFFICE_ENVIRONMENTS[name];
  return [
    '# Generated by scripts/agent-office-config.mjs. Do not edit or commit.',
    `name = ${tomlString(env.project)}`,
    `pages_build_output_dir = ${tomlString('./public')}`,
    `compatibility_date = ${tomlString(COMPATIBILITY_DATE)}`,
    '',
    '[vars]',
    `APP_ORIGIN = ${tomlString(env.appOrigin)}`,
    `FIREBASE_PROJECT_ID = ${tomlString(env.firebaseProjectId)}`,
    '',
  ].join('\n');
}

/** R65: the text of public/version.txt, the full sha this deployment serves. */
export function versionText(sha) {
  if (!/^[0-9a-f]{40}$/.test(String(sha))) throw new Error(`"${sha}" is not a full sha`);
  return `${sha}\n`;
}

/**
 * R48a: the text of public/app/env.json, the Firebase web config the page signs in with
 * (agent-office/public/app/live.js reads it). `vars` holds the environment's VITE_FIREBASE_*
 * variables, the same ones the Taskfolio build uses. Throws on a missing value, a key that is not a
 * Firebase web API key, or a project other than this environment's.
 * @param {string} name `staging` or `prod`
 * @param {Record<string, string | undefined>} vars
 */
export function envJson(name, vars) {
  if (!Object.hasOwn(AGENT_OFFICE_ENVIRONMENTS, name)) {
    throw new Error(`Unknown environment "${name}". Expected one of: ${Object.keys(AGENT_OFFICE_ENVIRONMENTS).join(', ')}`);
  }
  const keys = ['VITE_FIREBASE_API_KEY', 'VITE_FIREBASE_AUTH_DOMAIN', 'VITE_FIREBASE_PROJECT_ID', 'VITE_FIREBASE_APP_ID'];
  for (const k of keys) if (!vars[k]) throw new Error(`${k} is not set for the Agent Office ${name} environment.`);
  const apiKey = String(vars.VITE_FIREBASE_API_KEY);
  if (!/^AIza[0-9A-Za-z_-]{31,}$/.test(apiKey)) throw new Error('VITE_FIREBASE_API_KEY is not a Firebase web API key (expected AIza... of at least 35 characters).');
  const projectId = String(vars.VITE_FIREBASE_PROJECT_ID);
  const want = AGENT_OFFICE_ENVIRONMENTS[name].firebaseProjectId;
  if (projectId !== want) throw new Error(`VITE_FIREBASE_PROJECT_ID is ${projectId}, not ${want}, the project of the ${name} environment.`);
  const firebase = { apiKey, authDomain: String(vars.VITE_FIREBASE_AUTH_DOMAIN), projectId, appId: String(vars.VITE_FIREBASE_APP_ID) };
  return `${JSON.stringify({ firebase })}\n`;
}

/*
 * The one place the Jira proxy's per-environment configuration is written, per the 23 Sep 2026
 * decision in docs/DECISION_LOG.md ("Host the Jira proxy on its own Cloudflare Pages projects,
 * with CORS for the app origin only").
 *
 * The pure half; the command line wrapper is scripts/jira-proxy-config.mjs.
 * `node scripts/jira-proxy-config.mjs staging` writes `wrangler.toml` at the repository root for
 * `.github/workflows/deploy-jira-proxy.yml`, which then runs `wrangler pages deploy`. The file is
 * generated rather than committed because one repository deploys to two Pages projects, and
 * wrangler reads exactly one `wrangler.toml` from the working directory.
 *
 * Only plain variables live here: the Pages project name, the one app origin CORS grants
 * (`APP_ORIGIN`), and the Firebase project whose ID tokens the proxy accepts. The two secrets,
 * `JIRA_AUTH` and `JIRA_SITE`, are set by the owner with `wrangler pages secret put` and are never
 * written by this script, the workflow or anything else in the repository.
 *
 * `scripts/lib/jira-proxy.test.mjs` checks each entry against firebase.json, so the origin the
 * proxy grants and the origin the app's CSP allows cannot drift apart.
 */
export const COMPATIBILITY_DATE = '2026-05-01';

/* The static directory wrangler needs beside the functions. It holds one robots.txt and nothing
   else: the project serves the API, not pages. */
export const PUBLIC_DIR = 'jira-proxy-public';

export const JIRA_PROXY_ENVIRONMENTS = {
  staging: {
    project: 'taskfolio-api-staging',
    apiOrigin: 'https://taskfolio-api-staging.pages.dev',
    appOrigin: 'https://taskfolio-staging.web.app',
    firebaseProjectId: 'taskfolio-staging',
    hostingTarget: 'staging',
  },
  prod: {
    project: 'taskfolio-api-prod',
    apiOrigin: 'https://taskfolio-api-prod.pages.dev',
    appOrigin: 'https://skilllane-taskfolio.web.app',
    firebaseProjectId: 'taskfolio-prod',
    hostingTarget: 'prod',
  },
};

function tomlString(value) {
  if (!/^[A-Za-z0-9:/._-]+$/.test(value)) throw new Error(`Refusing to write an unexpected value into wrangler.toml: ${value}`);
  return `"${value}"`;
}

/** The wrangler.toml text for `name`, or a thrown error for an environment that does not exist. */
export function wranglerToml(name) {
  if (!Object.hasOwn(JIRA_PROXY_ENVIRONMENTS, name)) {
    throw new Error(`Unknown environment "${name}". Expected one of: ${Object.keys(JIRA_PROXY_ENVIRONMENTS).join(', ')}`);
  }
  const env = JIRA_PROXY_ENVIRONMENTS[name];
  return [
    '# Generated by scripts/jira-proxy-config.mjs. Do not edit or commit.',
    `name = ${tomlString(env.project)}`,
    `pages_build_output_dir = ${tomlString(`./${PUBLIC_DIR}`)}`,
    `compatibility_date = ${tomlString(COMPATIBILITY_DATE)}`,
    '',
    '[vars]',
    `APP_ORIGIN = ${tomlString(env.appOrigin)}`,
    `FIREBASE_PROJECT_ID = ${tomlString(env.firebaseProjectId)}`,
    '',
  ].join('\n');
}
